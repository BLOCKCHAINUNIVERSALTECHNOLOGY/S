"""S → Kotlin emitter (M9 / V0.0.9)

Generates readable Kotlin-style code from S AST.
Not a full compiler — a demonstration backend.
Interpreter remains the semantic source of truth.
"""

from .ast import *


class KotlinEmitter:
    def __init__(self):
        self.lines = []
        self.indent = 0

    def emit(self, line: str = ""):
        self.lines.append("    " * self.indent + line)

    def generate(self, program: Program) -> str:
        self.lines = []
        self.indent = 0
        self.emit("// Generated by S Language emitter V0.0.9")
        self.emit("// Backend: Kotlin (demonstration)")
        self.emit("")
        self.emit("fun main() {")
        self.indent += 1
        for stmt in program.statements:
            self.gen_stmt(stmt)
        self.indent -= 1
        self.emit("}")
        return "\n".join(self.lines)

    def gen_stmt(self, stmt):
        if isinstance(stmt, LetDecl):
            kw = "var" if stmt.mutable else "val"
            self.emit(f"{kw} {stmt.name} = {self.gen_expr(stmt.value)}")
        elif isinstance(stmt, Assign):
            self.emit(f"{stmt.name} = {self.gen_expr(stmt.value)}")
        elif isinstance(stmt, PrintStmt):
            args = ", ".join(self.gen_expr(a) for a in stmt.args)
            if len(stmt.args) == 1:
                self.emit(f"println({args})")
            else:
                self.emit(f'println(listOf({args}).joinToString(" "))')
        elif isinstance(stmt, ExprStmt):
            self.emit(self.gen_expr(stmt.expr))
        elif isinstance(stmt, IfStmt):
            self.emit(f"if ({self.gen_expr(stmt.condition)}) {{")
            self.indent += 1
            self.gen_block_body(stmt.then_branch)
            self.indent -= 1
            if stmt.else_branch:
                self.emit("} else {")
                self.indent += 1
                if isinstance(stmt.else_branch, IfStmt):
                    self.gen_stmt(stmt.else_branch)
                else:
                    self.gen_block_body(stmt.else_branch)
                self.indent -= 1
            self.emit("}")
        elif isinstance(stmt, LoopStmt):
            self.emit("while (true) {")
            self.indent += 1
            self.gen_block_body(stmt.body)
            self.indent -= 1
            self.emit("}")
        elif isinstance(stmt, ForStmt):
            # for i in 1..5  →  for (i in 1 until 5)
            it = stmt.iterable
            if isinstance(it, Range):
                self.emit(f"for ({stmt.var} in {self.gen_expr(it.start)} until {self.gen_expr(it.end)}) {{")
            else:
                self.emit(f"for ({stmt.var} in {self.gen_expr(it)}) {{")
            self.indent += 1
            self.gen_block_body(stmt.body)
            self.indent -= 1
            self.emit("}")
        elif isinstance(stmt, BreakStmt):
            self.emit("break")
        elif isinstance(stmt, NextStmt):
            self.emit("continue")
        elif isinstance(stmt, RetStmt):
            if stmt.value:
                self.emit(f"return {self.gen_expr(stmt.value)}")
            else:
                self.emit("return")
        elif isinstance(stmt, FnDecl):
            params = ", ".join(f"{n}: {self.kt_type(t)}" for n, t in stmt.params)
            ret = self.kt_type(stmt.return_type)
            self.emit(f"fun {stmt.name}({params}): {ret} {{")
            self.indent += 1
            self.gen_block_body(stmt.body)
            self.indent -= 1
            self.emit("}")
        elif isinstance(stmt, ClassDecl):
            self.emit(f"class {stmt.name} {{")
            self.indent += 1
            for m in stmt.methods:
                self.gen_stmt(m)
            self.indent -= 1
            self.emit("}")
        elif isinstance(stmt, SafeStmt):
            self.emit("try {")
            self.indent += 1
            self.gen_block_body(stmt.body)
            self.indent -= 1
            self.emit(f"}} catch ({stmt.rescue_name}: Exception) {{")
            self.indent += 1
            self.gen_block_body(stmt.rescue_body)
            self.indent -= 1
            self.emit("}")
        elif isinstance(stmt, AssertStmt):
            msg = self.gen_expr(stmt.message) if stmt.message else '"Assertion failed"'
            self.emit(f"require({self.gen_expr(stmt.condition)}) {{ {msg} }}")
        elif isinstance(stmt, UseDecl):
            self.emit(f"// use {'.'.join(stmt.path)}")
        elif isinstance(stmt, Block):
            self.gen_block_body(stmt)
        elif isinstance(stmt, SetMember):
            self.emit(f"{self.gen_expr(stmt.object)}.{stmt.name} = {self.gen_expr(stmt.value)}")
        else:
            self.emit(f"/* unsupported: {type(stmt).__name__} */")

    def gen_block_body(self, block):
        if isinstance(block, Block):
            for s in block.stmts:
                self.gen_stmt(s)
        else:
            self.gen_stmt(block)

    def gen_expr(self, expr) -> str:
        if isinstance(expr, IntLit):
            return str(expr.value)
        if isinstance(expr, DecLit):
            return str(expr.value)
        if isinstance(expr, StrLit):
            return '"' + expr.value.replace('\\', '\\\\').replace('"', '\\"') + '"'
        if isinstance(expr, BoolLit):
            return "true" if expr.value else "false"
        if isinstance(expr, NilLit):
            return "null"
        if isinstance(expr, Ident):
            return expr.name
        if isinstance(expr, ThisLit):
            return "this"
        if isinstance(expr, Group):
            return f"({self.gen_expr(expr.expr)})"
        if isinstance(expr, Unary):
            op = "!" if expr.op == "not" else expr.op
            return f"{op}{self.gen_expr(expr.expr)}"
        if isinstance(expr, Binary):
            op_map = {"and": "&&", "or": "||", "==": "==", "!=": "!=",
                      "+": "+", "-": "-", "*": "*", "/": "/", "%": "%",
                      "<": "<", ">": ">", "<=": "<=", ">=": ">="}
            op = op_map.get(expr.op, expr.op)
            return f"({self.gen_expr(expr.left)} {op} {self.gen_expr(expr.right)})"
        if isinstance(expr, Call):
            args = ", ".join(self.gen_expr(a) for a in expr.args)
            return f"{self.gen_expr(expr.callee)}({args})"
        if isinstance(expr, ListLit):
            els = ", ".join(self.gen_expr(e) for e in expr.elements)
            return f"listOf({els})"
        if isinstance(expr, MapLit):
            pairs = ", ".join(f"{self.gen_expr(k)} to {self.gen_expr(v)}" for k, v in expr.entries)
            return f"mapOf({pairs})"
        if isinstance(expr, Index):
            return f"{self.gen_expr(expr.object)}[{self.gen_expr(expr.index)}]"
        if isinstance(expr, Range):
            return f"{self.gen_expr(expr.start)} until {self.gen_expr(expr.end)}"
        if isinstance(expr, NewExpr):
            args = ", ".join(self.gen_expr(a) for a in expr.args)
            return f"{expr.class_name}({args})"
        if isinstance(expr, Member):
            return f"{self.gen_expr(expr.object)}.{expr.name}"
        return f"/*?{type(expr).__name__}*/"

    def kt_type(self, t: str) -> str:
        return {
            "int": "Int", "dec": "Double", "str": "String",
            "bool": "Boolean", "unit": "Unit", "list": "List<*>",
            "map": "Map<String, *>",
        }.get(t, t)
